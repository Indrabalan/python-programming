
# Match case

day_no = int(input("Enter day no :\n"))

match(day_no):
    case 1:
        print("Monday")
    case 2:
        print("Tuesday")
    case 3:
        print("Wednesday")
    case 4:
        print("Thursday")
    case 5:
        print("Friday")
    case 6:
        print("Saturday")     
    case 7:
        print("Sunday")                  
       