# In Python, variables are used to store data that can be used
# and manipulated throughout a program.
# A variable is created when you assign a value to it
# using the assignment operator (=).

age = 34       # integer
name = "Harry" # string
cgpa = 4.55    # float


# Rules for defining variables in Python

# 1. Variable names must start with a letter (a-z, A-Z)
#    or an underscore (_).
# 2. They can contain letters, numbers, and underscores.
# 3. Variable names are case-sensitive (age and Age are different).
# 4. Python keywords (e.g., if, for, while) cannot be
#    used as variable names.


# 34age = 4    # Invalid: Cannot start with a number

age = 32       # Valid: Starts with a letter

# a$$ge = 45   # Invalid: Cannot contain $ or spaces

__age = 34     # Valid

__nice_45 = 34 # Valid

a_b_c_7 = "Sam" # Valid