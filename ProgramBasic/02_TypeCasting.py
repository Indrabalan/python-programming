#Type Casting

num1 = 120
print(num1)
print(type(num1))

num_2 = "130"
print(num_2)
print(type(num_2))

num_3 = 140
print(num_3)
print(type(num_3))

#str to int

c = int(num_2)
print(c)
print(type(c))


#int to str
d = str(num_3)
print(d)
print(type(d))


#convert float to integer

num_4 = 10.5
print(num_4)
print(type(num_4))

e = int(num_4)
print(e)
print(type(e))